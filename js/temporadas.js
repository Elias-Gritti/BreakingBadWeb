const seasonTabs = document.querySelectorAll(".season-tab");
const seasonPanel = document.querySelector("#season-panel");

function renderSeason(seasonNumber) {
	const season = seasonData[seasonNumber];
	if (!season || !seasonPanel) return;

	const episodeMarkup = season.episodes.map((episode, index) => `
		<article class="episode-card">
			<span>Episodio ${index + 1}</span>
			<h4>${episode[0]}</h4>
			<p>${episode[1]}</p>
		</article>
	`).join("");

	seasonPanel.innerHTML = `
		<div class="season-panel-content">
			<article class="season-entry">
				<p class="section-label">Temporada ${seasonNumber}</p>
				<h3>${season.title}</h3>
				<p>${season.description}</p>
				<div class="episode-grid">${episodeMarkup}</div>
			</article>
		</div>
	`;
}

function selectSeason(tab) {
	const selectedSeason = tab.dataset.season;
	seasonTabs.forEach((seasonTab) => {
		const isActive = seasonTab === tab;
		seasonTab.classList.toggle("active", isActive);
		seasonTab.setAttribute("aria-expanded", String(isActive));
	});

	seasonPanel.classList.remove("is-open");
	window.setTimeout(() => {
		renderSeason(selectedSeason);
		seasonPanel.classList.add("is-open");
		seasonPanel.scrollIntoView({ behavior: "smooth", block: "start" });
	}, 180);
}

seasonTabs.forEach((tab) => {
	tab.addEventListener("click", () => selectSeason(tab));
});

renderSeason("1");
window.requestAnimationFrame(() => seasonPanel?.classList.add("is-open"));
